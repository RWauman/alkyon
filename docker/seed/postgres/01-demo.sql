SELECT 1000 + (n / 6),
       (n % 6)::smallint,
       1 + (n % 250),
       'SKU-' || lpad((n % 90)::text, 4, '0'),
       1 + (n % 7),
       (9.99 + (n % 40))::numeric(12,4),
       CASE WHEN n % 4 = 0 THEN NULL ELSE DATE '2025-01-01' + (n % 300) END,
       CASE WHEN n % 10 = 0 THEN decode(md5(n::text), 'hex') END
FROM generate_series(0, 1499) AS n;

